"""Rebuild the site's data (site/data/site-data.js). Run after locking a week or scoring results, then commit + push.

    conda run -n nfl-ats python scripts/build_site.py
    open site/index.html          # view locally
"""

import json

from nfl_ats.data import PROJECT_ROOT
from nfl_ats.ledger import load_schedules_for_ledger
from nfl_ats.site import backtest_summary, build_site_data

SEASON = 2026
OUT = PROJECT_ROOT / "site" / "data" / "site-data.js"


def main() -> None:
    schedules = load_schedules_for_ledger(SEASON, refresh=True)
    data = build_site_data(schedules, SEASON, backtest=backtest_summary(schedules))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("// Generated by scripts/build_site.py. Do not edit by hand.\nwindow.SITE_DATA = "
                   + json.dumps(data, indent=1) + ";\n")
    live = [w["week"] for w in data["weeks"] if w["mode"] == "live"]
    print(f"Wrote {OUT}: live weeks {live}, record games {data['record']['games']}, "
          f"current week {data['meta']['current_week']}, backtest {data['backtest']}")


if __name__ == "__main__":
    main()
